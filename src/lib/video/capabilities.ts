import { getConfig } from "@/lib/config";
import { pickModel } from "@/lib/creatives/concept-writer";
import type { ProviderCapabilities } from "@/lib/video/pipeline-types";

/**
 * What the providers configured here can really do, so nothing downstream assumes a feature that is
 * not there. Every gap names what is done instead. Read from the repository's actual integrations:
 *  - Seedance (BytePlus ModelArk) takes reference images, first/last frames and a reference video,
 *    and generates the voice itself from the prompt text.
 *  - There is no separate speech provider, no SSML, no phoneme dictionary and no lip-sync control.
 *  - OpenAI Whisper (word timestamps) is the only audio evidence, and needs OPENAI_API_KEY.
 *  - Frame inspection and OCR come from a vision-capable language model (pickModel), not a dedicated OCR engine.
 */
export function providerCapabilities(): ProviderCapabilities {
  const config = getConfig();
  const transcription = Boolean(config.OPENAI_API_KEY);
  const visionReview = pickModel() !== null;
  const gaps: string[] = [
    "No SSML, phoneme or pronunciation-dictionary support: the voice is generated by the video model from the prompt, so terms are handled by adapting the spoken wording only (display text stays correct).",
    "Narration cannot be synthesised before the picture: it is generated together with each clip. Scene timing is derived from the measured speech after generation, and clips whose speech is cut off or runs over are regenerated.",
    "Lip-sync cannot be controlled or separately validated; it comes from the model's own audio-video generation. Mouth movement is checked from sampled frames and the transcript only.",
    "Screens are composited flat (a verified screenshot placed over footage). Perspective tracking onto a screen in the footage is not implemented.",
  ];
  if (!transcription) gaps.push("No OPENAI_API_KEY: speech cannot be transcribed, so captions are evenly spaced and pronunciation cannot be checked against the audio.");
  if (!visionReview) gaps.push("No language model with vision is configured (ANTHROPIC_API_KEY or OPENAI_API_KEY): clips and the final video cannot be inspected for faces, hands, stray text or invented logos, so they stay unresolved instead of being approved.");
  return {
    referenceImages: true,
    firstLastFrame: true,
    nativeAudio: true,
    ssml: false,
    phonemeDictionary: false,
    lipSync: "native_model_audio",
    transcription,
    visionReview,
    perspectiveScreenTracking: false,
    gaps,
  };
}
